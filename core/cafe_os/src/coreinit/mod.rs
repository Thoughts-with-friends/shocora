/// Library name used in export tables.
pub const LIBRARY: &str = "coreinit";

/// coreinit state outside guest memory.
#[derive(serde::Serialize, serde::Deserialize, Debug, Default)]
pub struct CoreinitState {
    pub heaps: mem::HeapTable,
    pub alarms: alarm::Alarms,
    pub fs: fs::FsState,
    /// `OSThread` of the main thread.
    pub main_thread: u32,
    pub threads: thread::Scheduler,
    /// Default thread of each core (core 1's is the main thread).
    pub default_threads: [u32; 3],
    /// `OSGetSystemMessageQueue` result (0 until first call).
    pub system_message_queue: u32,
    pub interrupts_enabled: bool,
    /// `OSSystemInfo` returned by `OSGetSystemInfo` (0 until first call).
    pub system_info: u32,
    pub home_button_menu: bool,
    /// `(alloc, free)` function pointers set by `OSDynLoad_SetAllocator`.
    pub dynload_allocator: (u32, u32),
    pub locked_cache: lc::LockedCache,
    pub shared_data: shared_data::SharedData,
    pub mp: mp::MpState,
    pub unit_heaps: mem::unit_api::UnitHeaps,
    /// Function table of `MEMInitAllocatorForDefaultHeap` (0 until first call).
    pub default_allocator_functions: u32,
    /// Slot returned by `__ghs_flock_ptr` (0 until first call).
    pub ghs_flock: u32,
    pub errno: u32,
    /// Stack pointer and return address under each thread's running fibers.
    pub fibers: std::collections::HashMap<u32, Vec<(u32, u32)>>,
    pub serial_interface: hw_interface::SerialInterface,
    /// Initial thread-local storage of the RPX, copied per thread by `__tls_get_addr`.
    pub tls_image: Option<wiiu_rpl::TlsImage>,
}

