/// Everything an HLE function may touch.
pub struct HleContext<'a> {
    /// The calling core.
    pub cpu: &'a mut CpuState,
    pub memory: &'a mut Memory,
    pub os: &'a mut CafeOs,
    pub gpu: &'a mut Gpu,
    pub iosu: &'a mut Iosu,
}

/// A failure that stops emulation.
#[derive(Debug, thiserror::Error)]
pub enum HleError {
    #[error(transparent)]
    Memory(#[from] MemoryError),
    #[error(transparent)]
    Gpu(#[from] GpuError),
    #[error("guest fatal error: {0}")]
    Fatal(String),
}

pub type HleResult = Result<(), HleError>;

/// Signature of every HLE thunk.
pub type HleFn = fn(&mut HleContext<'_>) -> HleResult;

/// A function exported by an HLE library (generated by `#[hle_export]`).
#[derive(Clone, Copy)]
pub struct HleExport {
    pub library: &'static str,
    pub name: &'static str,
    pub function: HleFn,
}

impl std::fmt::Debug for HleExport {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}::{}", self.library, self.name)
    }
}

/// Runs HLE function `index` for the core in `ctx`.
///
/// Calls to imports shocora does not implement return 0 and are logged once.
///
/// # Errors
/// Propagates the function's failure.
pub fn dispatch(ctx: &mut HleContext<'_>, index: u32) -> HleResult {
    // A call that blocks is re-executed later, so it must find its arguments
    // untouched: undo the return value the thunk wrote.
    let arguments = (ctx.cpu.gpr[3], ctx.cpu.gpr[4], ctx.cpu.fpr[1]);
    let generation = ctx.os.callbacks.generation;
    // A callback can borrow the core of a thread that is already blocked; its
    // calls did not block and keep their results.
    let blocked_before = ctx.os.coreinit.threads.current_is_blocked();
    call(ctx, index)?;
    let callback_switched = ctx.os.callbacks.generation != generation;
    if !callback_switched && !blocked_before && ctx.os.coreinit.threads.current_is_blocked() {
        (ctx.cpu.gpr[3], ctx.cpu.gpr[4], ctx.cpu.fpr[1]) = arguments;
    }
    // Scheduling waits until no callback is borrowing the core.
    if !ctx.os.callback_active_on(ctx.cpu.core_id()) {
        // Blocking/yielding calls ask for a scheduling decision once they return.
        if let Some(mode) = ctx.os.coreinit.threads.take_request() {
            ctx.os.schedule(ctx.cpu, ctx.memory, mode);
        }
        ctx.os.start_callback(ctx.cpu, ctx.memory)?;
    }
    Ok(())
}

fn call(ctx: &mut HleContext<'_>, index: u32) -> HleResult {
    ctx.os.gx2.active_thread = ctx.os.coreinit.threads.current;
    ctx.os.registry.note_call(index);
    if ctx.os.registry.is_traced(index) {
        let thread = ctx.os.coreinit.threads.current;
        let r = &ctx.cpu.gpr;
        // The callers above `lr`, along the stack's back chain.
        let mut callers = Vec::new();
        let mut frame = ctx.memory.read_u32(r[1]).unwrap_or(0);
        while callers.len() < TRACED_CALLERS && frame != 0 {
            let Ok(caller) = ctx.memory.read_u32(frame + 4) else { break };
            callers.push(format!("{caller:#010x}"));
            frame = ctx.memory.read_u32(frame).unwrap_or(0);
        }
        log::info!(
            "{} thread {thread:#x} lr {:#010x} < {} ({:#x}, {:#x}, {:#x}, {:#x}, {:#x}, {:#x})",
            ctx.os.registry.name_of(index),
            ctx.cpu.lr,
            callers.join(" < "),
            r[3],
            r[4],
            r[5],
            r[6],
            r[7],
            r[8]
        );
    }
    let (lr, arg) = (ctx.cpu.lr, ctx.cpu.gpr[3]);
    let result = call_entry(ctx, index);
    ctx.os.registry.record_trace(index, lr, arg, ctx.cpu.gpr[3]);
    result
}

/// Callers listed per call of a function in `SHOCORA_TRACE_HLE`.
const TRACED_CALLERS: usize = 10;

fn call_entry(ctx: &mut HleContext<'_>, index: u32) -> HleResult {
    if let Some(function) = ctx.os.registry.function(index) {
        return function(ctx);
    }
    // Titles call some missing functions millions of times: only the first call looks
    // the entry up (cloning its names), the others just return 0.
    if !ctx.os.registry.contains(index) {
        return Err(HleError::Fatal(format!("bad HLE index {index}")));
    }
    if ctx.os.registry.note_missing_call(index) {
        if let Some(Entry::Missing { library, name }) = ctx.os.registry.entry(index) {
            log::warn!("unimplemented: {library}::{name} (lr {:#010x})", ctx.cpu.lr);
        }
    }
    ctx.cpu.gpr[3] = 0;
    Ok(())
}
